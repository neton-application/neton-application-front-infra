import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { createRequire } from "node:module";
import { realpathSync } from "node:fs";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, "..");
const require = createRequire(realpathSync(resolve(root, "../neton-application-front/node_modules/playwright/package.json")));
const { chromium } = require("playwright");
const server = spawn(process.execPath, [resolve(root, "tests/browser-server.mjs")], { cwd: root, stdio: ["ignore", "pipe", "inherit"] });
let browser;
try {
  await new Promise((ok, fail) => {
    const timer = setTimeout(() => fail(Error("fixture start timed out")), 20_000);
    server.once("exit", (code) => { clearTimeout(timer); fail(Error(`fixture exited ${code}`)); });
    server.stdout.on("data", (data) => { if (data.toString().includes("UI fixture")) { clearTimeout(timer); ok(); } });
  });
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage();
  const url = "http://127.0.0.1:58151";
  await page.goto(url);
  await page.getByRole("button", { name: "新增文件配置", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "新增文件配置", exact: true });
  await dialog.getByRole("textbox", { name: "配置名称", exact: true }).fill("Browser local");
  await dialog.getByRole("textbox", { name: "存储子目录（相对于部署根目录）", exact: true }).fill("photos");
  await page.request.get(`${url}/fixture/fail`);
  await dialog.getByRole("button", { name: "保存", exact: true }).click();
  await dialog.getByRole("alert").waitFor();
  assert.equal(await dialog.getByRole("textbox", { name: "配置名称", exact: true }).inputValue(), "Browser local");
  await dialog.getByRole("button", { name: "保存", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  await page.getByRole("cell", { name: "Browser local", exact: true }).waitFor();
  const localRow = page.getByRole("row").filter({ has: page.getByRole("cell", { name: "Browser local", exact: true }) });
  await localRow.getByRole("cell", { name: "未测试", exact: true }).waitFor();
  await localRow.getByRole("button", { name: "测试读写和删除", exact: true }).click();
  await page.getByRole("alertdialog", { name: "测试读写和删除", exact: true }).getByRole("button", { name: "确认", exact: true }).click();
  const resultDialog = page.getByRole("dialog", { name: "测试通过", exact: true });
  await resultDialog.getByText("「Browser local」的写入、读取及删除测试全部通过。", { exact: true }).waitFor();
  await resultDialog.getByRole("button", { name: "确认", exact: true }).click();
  await localRow.getByRole("cell", { name: "测试通过", exact: true }).waitFor();
  await page.reload();
  await localRow.getByRole("cell", { name: "测试通过", exact: true }).waitFor();
  await page.getByRole("button", { name: "新增文件配置", exact: true }).click();
  await dialog.getByRole("textbox", { name: "配置名称", exact: true }).fill("Browser S3");
  await dialog.getByRole("combobox", { name: "存储类型", exact: true }).click();
  await page.getByRole("option", { name: "S3 兼容", exact: true }).click();
  for (const [name, value] of [["S3 兼容端点（不含路径）", "https://oss-ap-southeast-1.aliyuncs.com"], ["区域", "us-east-1"], ["Bucket", "media"], ["Access Key 环境变量名", "NETON_STORAGE_ACCESS"], ["Secret Key 环境变量名", "NETON_STORAGE_SECRET"]]) await dialog.getByRole("textbox", { name, exact: true }).fill(value);
  assert.equal(await dialog.getByRole("combobox", { name: "主配置", exact: true }).count(), 0);
  assert.equal(await dialog.getByRole("textbox", { name: "存储子目录（相对于部署根目录）", exact: true }).count(), 0);
  await dialog.getByRole("button", { name: "保存", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  const row = page.getByRole("row").filter({ has: page.getByRole("cell", { name: "Browser S3", exact: true }) });
  await row.getByRole("button", { name: "编辑文件配置", exact: true }).click();
  const editing = page.getByRole("dialog", { name: "编辑文件配置", exact: true });
  await editing.waitFor();
  assert.equal(await editing.getByRole("textbox", { name: "Bucket", exact: true }).inputValue(), "media");
  await editing.getByRole("button", { name: "取消", exact: true }).click();
  await page.request.get(`${url}/fixture/fail-probe`);
  await row.getByRole("button", { name: "测试读写和删除", exact: true }).click();
  const testDialog = page.getByRole("alertdialog", { name: "测试读写和删除", exact: true });
  await testDialog.getByRole("button", { name: "确认", exact: true }).click();
  await testDialog.getByText(/阿里云 OSS 服务器拒绝写入测试文件.*HTTP 403.*FILE_STORAGE_WRITE_DENIED.*PutObject/).waitFor();
  await testDialog.getByRole("button", { name: "取消", exact: true }).click();
  await row.getByRole("cell", { name: "测试未通过", exact: true }).waitFor();
  await localRow.getByRole("button", { name: "更多操作" }).click();
  assert.equal(await page.getByRole("menuitem", { name: "切换主配置后可禁用" }).isEnabled(), false);
  assert.equal(await page.getByRole("menuitem", { name: "删除文件配置" }).count(), 0);
  await page.keyboard.press("Escape");
  await row.getByRole("button", { name: "更多操作" }).click();
  await page.getByRole("menuitem", { name: "禁用配置", exact: true }).click();
  await page.getByRole("alertdialog", { name: "禁用配置", exact: true }).getByRole("button", { name: "确认" }).click();
  await row.getByRole("cell", { name: "已禁用", exact: true }).waitFor();
  await page.getByRole("combobox", { name: "状态", exact: true }).click();
  await page.getByRole("option", { name: "已禁用", exact: true }).click();
  await page.getByRole("button", { name: "查询", exact: true }).click();
  await localRow.waitFor({ state: "hidden" });
  await page.getByRole("button", { name: "重置", exact: true }).click();
  await localRow.waitFor();
  await row.getByRole("button", { name: "更多操作" }).click();
  await page.getByRole("menuitem", { name: "启用配置", exact: true }).click();
  await page.getByRole("alertdialog", { name: "启用配置", exact: true }).getByRole("button", { name: "确认" }).click();
  await row.getByRole("cell", { name: "启用", exact: true }).waitFor();
  const requests = await (await page.request.get(`${url}/fixture/requests`)).json();
  const s3 = requests.find((r) => r.path.endsWith("/create") && r.body?.name === "Browser S3");
  assert.equal(s3.body.config.basePath, ""); assert.equal(s3.body.config.secretKeyEnv, "NETON_STORAGE_SECRET");
  assert.equal(s3.body.config.secretKey, undefined);
  assert.equal(s3.body.master, undefined);
  assert.ok(requests.some((r) => r.method === "POST" && r.path.endsWith("/test/1")));
  assert.ok(requests.some((r) => r.method === "PUT" && r.path.endsWith("/update-status/2") && r.query.status === "0"));
  assert.ok(requests.some((r) => r.path.endsWith("/page") && r.query.status === "0"));
  assert.equal(requests.some((r) => r.method === "DELETE"), false);
  await page.goto(`${url}/?readonly&lang=en`);
  await page.getByRole("heading", { name: "File storage", exact: true }).waitFor();
  assert.equal(await page.getByRole("button", { name: "Create file configuration", exact: true }).count(), 0);
  assert.equal(await page.getByRole("button", { name: "Edit file configuration", exact: true }).count(), 0);
  console.log("FILE_CONFIG_BROWSER_PASS dynamicFields=true saveFailure=true edit=true permissions=true bilingual=true");
} finally {
  if (browser) await browser.close();
  server.kill("SIGTERM");
  await new Promise((ok) => server.exitCode !== null ? ok() : server.once("exit", ok));
}
